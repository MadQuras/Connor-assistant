def _courtesy_kind(low: str) -> str | None:
    if _contains_any(low, _COURTESY_THANKS):
        return "thanks"
    if _contains_any(low, _COURTESY_HELLO):
        return "hello"
    if _contains_any(low, _COURTESY_BYE):
        return "bye"
    if _contains_any(low, _COURTESY_PRAISE):
        return "praise"
    return None


def route(text: str) -> Tuple[str, str]:
    low = text.lower().strip()

    # ── DISMISS («отойди пока») — до courtesy (иначе «пока» = bye) ──
    if _is_dismiss(low):
        return "DISMISS", ""

    # ── COURTESY (бытовые фразы) ─────────────────────────────────
    courtesy = _courtesy_kind(low)
    if courtesy:
        return "COURTESY", courtesy

    # ── ACTIVITY (время за ПК) ───────────────────────────────────
    if _contains_any(low, _ACTIVITY_KW):
        return "ACTIVITY", ""

    # ── Recycle bin (before generic APPS) ────────────────────────
    if "корзин" in low and any(x in low for x in ("очист", "удали", "очисти", "пусти", "почисти")):
        return "APPS", "очисти корзину"

    # ── Specific folders ─────────────────────────────────────────
    if any(x in low for x in ("загрузк", "загруз", "загрузки", "downloads")):
        return "APPS", "загрузки"
    if any(x in low for x in ("документ", "documents")) and "рабоч" not in low:
        return "APPS", "документы"
    if "рабоч" in low and any(x in low for x in ("папк", "стол", "desktop")):
        return "APPS", "рабочая папка"

    # ── WEATHER (до QA — «какая погода» не уходит в Q&A) ─────────
    if _is_weather(low):
        return "WEATHER", ""

    # ── QA (краткий фактический ответ) ───────────────────────────
    if _is_qa(low):
        return "QA", _qa_arg(low)

    # ── SEARCH (открыть браузер) ─────────────────────────────────
    if _contains_any(low, _SEARCH_KW):
        return "SEARCH", _after(low, (
            "найди", "найти", "поищи", "загугли", "загуглить",
            "гугл", "ищи", "search", "find",
        ))

    # ── VOLUME (before APPS to avoid "включи" conflict) ──────────
    if _contains_any(low, _VOLUME_UP_KW):
        return "VOLUME", "up"
    if _contains_any(low, _VOLUME_DOWN_KW):
        return "VOLUME", "down"
    if _contains_any(low, _VOLUME_KW):
        return "VOLUME", _volume_arg(low)

    # ── MUSIC (before APPS — "включи трек" must hit MUSIC) ───────
    # Phrase "открой музыку" / "включи музыку" — explicit music
    if _music_explicit(low):
        return "MUSIC", _after(low, (
            "включи", "поставь", "воспроизведи", "найди", "открой", "запусти",
        )) or low

    # ── SHUTDOWN ─────────────────────────────────────────────────
    if _contains_any(low, _SHUTDOWN_KW):
        return "SHUTDOWN", ""

    # ── LOCK ─────────────────────────────────────────────────────
    if _contains_any(low, _LOCK_KW):
        return "LOCK", ""

    # ── APPS ─────────────────────────────────────────────────────
    if _contains_any(low, _APPS_KW):
        remainder = _after(low, (
            "открой", "запусти", "включи", "стартуй",
            "покажи", "зайди в", "перейди в",
            "open", "launch", "run", "start",
        ))
        # If no verb was found but a known app name is in text, use full text
        return "APPS", remainder or low

    # ── TIME ─────────────────────────────────────────────────────
    if _contains_any(low, _TIME_KW):
        return "TIME", ""

    # ── PLANS ────────────────────────────────────────────────────
    if _contains_any(low, _PLANS_KW):
        arg = _after(low, ("запомни", "запиши", "напомни", "заметки")) or low
        return "PLANS", arg

    # ── Residual music keywords (трек / песня without explicit verb) ──
    if _contains_any(low, _MUSIC_KW):
        return "MUSIC", low

    return "UNKNOWN", ""


# ─── Helpers ─────────────────────────────────────────────────────────────────

def _is_dismiss(low: str) -> bool:
    from core.dismiss import is_dismiss_phrase
    return is_dismiss_phrase(low)


def _is_weather(low: str) -> bool:
    return _contains_any(low, _WEATHER_KW) or "погод" in low


def _is_qa(low: str) -> bool:
    """Фактический вопрос — не время/погода/болтовня."""
    if _is_weather(low):
        return False
    if "?" in low:
        if any(x in low for x in ("сколько времени", "который час", "какое время", "какая погода")):
            return False
        return True
    if _contains_any(low, _QA_KW):
        if any(x in low for x in ("кто ты", "что ты", "как дела", "как ты")):
            return False
        return True
    if re.match(r"^(когда|где|сколько|какой|какая|какие|почему|зачем)\b", low):
        if "сколько" in low and any(x in low for x in ("времени", "час", "минут")):
            return False
        return True
    return False


def _qa_arg(low: str) -> str:
    """Текст вопроса без лишних префиксов."""
    stripped = _after(low, (
        "скажи про", "расскажи про", "расскажи о", "скажи о",
        "что такое", "кто такой", "кто такая",
    ))
    return stripped or low


def _contains_any(text: str, keywords: set) -> bool:
    """True if *any* keyword is a substring of text."""
    return any(kw in text for kw in keywords)


def _music_explicit(low: str) -> bool:
    """True if the phrase is clearly about music (transport controls or explicit music trigger)."""
    return any(kw in low for kw in (
        "музык", "трек", "трэк", "песн", "плейлист", "плей", "lune", "лун",
        "воспроизвед", "следующ", "предыдущ",
        "пауз", "стоп", "поставь",
        "возобнов", "продолж", "resume", "unpause",
    ))


def _after(low: str, triggers: tuple) -> str:
    """Return text after the first matching trigger keyword."""
    for t in triggers:
        idx = low.find(t)
        if idx != -1:
            return low[idx + len(t):].strip()
    return ""


def _volume_arg(low: str) -> str:
    if _contains_any(low, _VOLUME_DOWN_KW) or any(x in low for x in (
        "тише", "тиша", "тиши", "таша", "таши", "убавь", "уменьш", "ниже", "тихо", "скрути",
    )):
        return "down"
    if _contains_any(low, _VOLUME_UP_KW) or any(x in low for x in ("громче", "прибавь", "увеличь", "выше")):
        return "up"
    m = re.search(r"(\d{1,3})", low)
    return m.group(1) if m else "up"
